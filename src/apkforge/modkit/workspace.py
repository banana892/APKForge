"""Isolated per-execution ModKit workspaces.

Layout::

    <base>/<execution-id>/
        input/input.apk      read-only staged copy; the ModKit never sees the original
        working/             the ModKit's cwd; also its HOME and TMPDIR
        output/              the only place an output is accepted from
        logs/                stdout.log, stderr.log, execution.log
        metadata/            request.json, result.json, provenance.json

Every execution gets a fresh directory (``exist_ok=False``); workspaces are never
reused across executions. Execution ids are generated by APKForge (UTC timestamp +
random suffix) and caller-supplied ids must be a single plain path component. No
path is ever derived from APK contents or from ModKit-supplied names.

Retention follows :class:`~apkforge.core.config.WorkspaceSettings`: a failed
execution is kept whole for diagnosis (``keep_on_failure``, default on); otherwise
input/, working/ and output/ are removed and logs/ and metadata/ are kept.
"""

from __future__ import annotations

import datetime
import hashlib
import os
import re
import shutil
import stat
import uuid
from pathlib import Path

from apkforge.core.exceptions import WorkspaceError

__all__ = ["ModKitWorkspace", "new_execution_id", "sha256_file"]

_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}")
_SUBDIRS = ("input", "working", "output", "logs", "metadata")
_DISPOSABLE = ("input", "working", "output")


def new_execution_id() -> str:
    stamp = datetime.datetime.now(datetime.UTC).strftime("%Y%m%dT%H%M%SZ")
    return f"mk-{stamp}-{uuid.uuid4().hex[:12]}"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _make_writable(root: Path) -> None:
    """Undo read-only modes so retention can delete what a ModKit left behind."""
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        for name in dirnames + filenames:
            p = Path(dirpath) / name
            try:
                if not p.is_symlink():
                    p.chmod(p.stat().st_mode | stat.S_IWUSR | stat.S_IRUSR | stat.S_IXUSR)
            except OSError:
                pass


class ModKitWorkspace:
    """Filesystem workspace for exactly one ModKit execution."""

    def __init__(self, root: Path, execution_id: str) -> None:
        self.root = root.resolve()
        self.execution_id = execution_id
        self.input_dir = self.root / "input"
        self.working_dir = self.root / "working"
        self.output_dir = self.root / "output"
        self.logs_dir = self.root / "logs"
        self.metadata_dir = self.root / "metadata"
        self.staged_input = self.input_dir / "input.apk"
        self.home_dir = self.working_dir / ".home"
        self.tmp_dir = self.working_dir / ".tmp"

    @classmethod
    def create(cls, base_dir: Path, execution_id: str | None = None) -> ModKitWorkspace:
        execution_id = execution_id or new_execution_id()
        if not _ID.fullmatch(execution_id) or ".." in execution_id:
            raise WorkspaceError(
                f"Invalid execution id {execution_id!r}: must be a single plain path component.",
                context="modkit-workspace",
            )
        try:
            base_dir = base_dir.resolve()
            base_dir.mkdir(parents=True, exist_ok=True)
            root = base_dir / execution_id
            root.mkdir(mode=0o700, exist_ok=False)
            ws = cls(root, execution_id)
            for name in _SUBDIRS:
                (ws.root / name).mkdir(mode=0o700)
            ws.home_dir.mkdir(mode=0o700)
            ws.tmp_dir.mkdir(mode=0o700)
        except OSError as exc:
            raise WorkspaceError(
                f"Failed to create ModKit workspace under {base_dir}: {exc}",
                context="modkit-workspace",
            ) from exc
        return ws

    def subpath(self, *parts: str) -> Path:
        """Path inside the workspace; rejects anything that would escape it."""
        candidate = (self.root / Path(*parts)).resolve()
        if not candidate.is_relative_to(self.root):
            raise WorkspaceError(
                f"Path traversal detected: {candidate} escapes workspace {self.root}",
                context="modkit-workspace",
            )
        return candidate

    def problems(self) -> list[str]:
        out: list[str] = []
        for name in _SUBDIRS:
            d = self.root / name
            if d.is_symlink() or not d.is_dir():
                out.append(f"{d} is not a directory")
            elif not os.access(d, os.W_OK | os.X_OK):
                out.append(f"{d} is not writable")
        return out

    def stage_input(self, apk: Path, expected_sha256: str) -> tuple[Path, str]:
        """Copy *apk* to ``input/input.apk`` (read-only) and verify the copy.

        Raises :class:`WorkspaceError` if the staged bytes differ from
        *expected_sha256* (the original's hash taken before staging).
        """
        dest = self.staged_input
        try:
            shutil.copyfile(apk, dest, follow_symlinks=True)
            dest.chmod(0o444)
        except OSError as exc:
            raise WorkspaceError(f"Failed to stage input: {exc}", context="modkit-stage") from exc
        staged = sha256_file(dest)
        if staged != expected_sha256:
            raise WorkspaceError(
                f"Staged input SHA-256 {staged} differs from original {expected_sha256}",
                context="modkit-stage",
            )
        return dest, staged

    def apply_retention(self, *, success: bool, keep: bool, keep_on_failure: bool) -> bool:
        """Delete files per the retention policy; returns True if the workspace is kept whole."""
        if keep or (not success and keep_on_failure):
            return True
        for name in _DISPOSABLE:
            target = self.root / name
            if target.is_symlink():
                target.unlink(missing_ok=True)
            elif target.exists():
                _make_writable(target)
                shutil.rmtree(target, ignore_errors=True)
        return False

    def remove(self) -> None:
        if self.root.exists():
            _make_writable(self.root)
            shutil.rmtree(self.root, ignore_errors=True)
