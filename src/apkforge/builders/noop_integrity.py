"""No-op rebuild integrity baseline.

Compares an original APK with its no-op rebuild to record what an unmodified
round trip preserves and what it changes. This is a *baseline* for later
semantic verification, not a semantic diff engine:

- native libraries (``lib/**/*.so``): expected byte-identical
- DEX: re-assembled from smali, byte differences expected (recorded only)
- ``resources.arsc``: regenerated by AAPT2, byte differences expected (recorded only)
- ``AndroidManifest.xml``: must parse; package, version and component counts compared
- signature files: original ``META-INF`` signature entries are replaced
"""

from __future__ import annotations

import contextlib
import re
import xml.etree.ElementTree as ET
import zipfile
from collections import Counter
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from pathlib import Path

__all__ = ["compare_noop_rebuild"]

_ANDROID_NS = "{http://schemas.android.com/apk/res/android}"
_SIG_FILE = re.compile(r"^META-INF/[^/]+\.(?:SF|RSA|DSA|EC|MF)$|^META-INF/MANIFEST\.MF$", re.I)
_COMPONENTS = (
    "uses-permission",
    "permission",
    "activity",
    "activity-alias",
    "service",
    "receiver",
    "provider",
)


def _manifest_summary(raw: bytes) -> dict[str, Any]:
    try:
        from androguard.core.axml import AXMLPrinter

        with contextlib.suppress(ImportError):
            from loguru import logger

            logger.disable("androguard")  # androguard logs every AXML chunk at DEBUG

        xml = AXMLPrinter(raw).get_xml()
        root = ET.fromstring(xml)  # noqa: S314 - androguard output of a local file
    except Exception as exc:  # pragma: no cover - parse failure is the reported outcome
        return {"parseable": False, "error": f"{type(exc).__name__}: {exc}"}
    counts = Counter(el.tag for el in root.iter() if el.tag in _COMPONENTS)
    uses_sdk = root.find("uses-sdk")
    return {
        "parseable": True,
        "package": root.get("package"),
        "version_code": root.get(f"{_ANDROID_NS}versionCode"),
        "version_name": root.get(f"{_ANDROID_NS}versionName"),
        "min_sdk": uses_sdk.get(f"{_ANDROID_NS}minSdkVersion") if uses_sdk is not None else None,
        "target_sdk": uses_sdk.get(f"{_ANDROID_NS}targetSdkVersion")
        if uses_sdk is not None
        else None,
        "components": {k: counts.get(k, 0) for k in _COMPONENTS},
    }


def compare_noop_rebuild(original: Path, rebuilt: Path) -> dict[str, Any]:
    """Return a JSON-serializable comparison of *original* and its no-op *rebuilt* APK."""
    with zipfile.ZipFile(original) as zo, zipfile.ZipFile(rebuilt) as zr:
        o_names, r_names = set(zo.namelist()), set(zr.namelist())

        def _read(z: zipfile.ZipFile, name: str) -> bytes:
            return z.read(name)

        # Native libraries
        o_libs = sorted(n for n in o_names if n.startswith("lib/") and n.endswith(".so"))
        lib_mismatch = [n for n in o_libs if n in r_names and _read(zo, n) != _read(zr, n)]
        lib_missing = [n for n in o_libs if n not in r_names]
        native = {
            "count": len(o_libs),
            "identical": len(o_libs) - len(lib_mismatch) - len(lib_missing),
            "mismatched": lib_mismatch,
            "missing_in_rebuilt": lib_missing,
            "all_identical": not lib_mismatch and not lib_missing,
        }

        # DEX (informational)
        dex_re = re.compile(r"^classes\d*\.dex$")
        o_dex = sorted(n for n in o_names if dex_re.match(n))
        r_dex = sorted(n for n in r_names if dex_re.match(n))
        dex = {
            "original_files": len(o_dex),
            "rebuilt_files": len(r_dex),
            "original_bytes": sum(zo.getinfo(n).file_size for n in o_dex),
            "rebuilt_bytes": sum(zr.getinfo(n).file_size for n in r_dex),
            "byte_identical_files": sum(
                1 for n in o_dex if n in r_names and _read(zo, n) == _read(zr, n)
            ),
            "same_file_set": o_dex == r_dex,
        }

        # resources.arsc (informational)
        arsc: dict[str, Any] = {
            "present_original": "resources.arsc" in o_names,
            "present_rebuilt": "resources.arsc" in r_names,
        }
        if arsc["present_original"] and arsc["present_rebuilt"]:
            arsc["original_bytes"] = zo.getinfo("resources.arsc").file_size
            arsc["rebuilt_bytes"] = zr.getinfo("resources.arsc").file_size
            arsc["byte_identical"] = _read(zo, "resources.arsc") == _read(zr, "resources.arsc")

        # Manifest
        o_man = (
            _manifest_summary(_read(zo, "AndroidManifest.xml"))
            if "AndroidManifest.xml" in o_names
            else {"parseable": False}
        )
        r_man = (
            _manifest_summary(_read(zr, "AndroidManifest.xml"))
            if "AndroidManifest.xml" in r_names
            else {"parseable": False}
        )
        same_keys = (
            "package",
            "version_code",
            "version_name",
            "min_sdk",
            "target_sdk",
            "components",
        )
        manifest = {
            "rebuilt_parseable": r_man.get("parseable", False),
            "byte_identical": "AndroidManifest.xml" in r_names
            and "AndroidManifest.xml" in o_names
            and _read(zo, "AndroidManifest.xml") == _read(zr, "AndroidManifest.xml"),
            "identity_and_component_counts_match": bool(
                o_man.get("parseable") and r_man.get("parseable")
            )
            and all(o_man.get(k) == r_man.get(k) for k in same_keys),
            "original": o_man,
            "rebuilt": r_man,
        }

        # Entry sets, excluding signature files which are expected to change
        o_content = {n for n in o_names if not _SIG_FILE.match(n)}
        r_content = {n for n in r_names if not _SIG_FILE.match(n)}
        entries = {
            "original_count": len(o_names),
            "rebuilt_count": len(r_names),
            # Apktool restores shortened resource paths (e.g. res/a.xml -> res/layout/x.xml),
            # so added/removed sets can be large; record counts plus a sample.
            "added_non_signature_count": len(r_content - o_content),
            "removed_non_signature_count": len(o_content - r_content),
            "added_non_signature_sample": sorted(r_content - o_content)[:10],
            "removed_non_signature_sample": sorted(o_content - r_content)[:10],
            "original_signature_files": sorted(o_names - o_content),
            "rebuilt_signature_files": sorted(r_names - r_content),
        }

    return {
        "native_libs": native,
        "dex": dex,
        "resources_arsc": arsc,
        "manifest": manifest,
        "entries": entries,
    }
